    check('Hub recovery reconnects clients','1 / 1' in page.locator('#send-result').inner_text())
    page.locator('#mode-p2p').click();idle(page)
    check('P2P mode creates six mesh links',page.evaluate('state.stats.activeLinks')==6)
    page.locator('[data-toggle-node="D"]').click();idle(page)
    send(page,'A','B','The surviving peers stay connected.')
    check('Peer failure preserves unrelated A-to-B delivery','1 / 1' in page.locator('#send-result').inner_text())
    send(page,'A','D','Offline peers cannot receive a message.')
    check('Offline peer delivery fails visibly','Recipient is offline' in page.locator('#send-result').inner_text())
