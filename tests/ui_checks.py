import json,sys,time
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
from browser_harness import setup,request,BROWSER
ROOT=Path(__file__).resolve().parents[1];EVIDENCE=ROOT/'evidence';EVIDENCE.mkdir(exist_ok=True)
checks=[];errors=[]
def check(name,condition=True):
    assert condition,name
    checks.append({'check':name,'passed':True})
def idle(page):
    page.wait_for_function('!localBusy && state && !state.busy')
    page.wait_for_timeout(150)
def send(page,sender,to,text):
    page.locator('#sender').select_option(sender)
    page.locator('#recipient').select_option(to)
    page.locator('#message-text').fill(text)
    page.locator('#send-message').click();idle(page)

request('/api/reset',{'method':'POST','headers':{'Content-Type':'application/json'},'body':json.dumps({'mode':'client-server','count':4,'delayMs':0})})
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=BROWSER,args=['--no-sandbox'])
    page=setup(browser,1600,1100)
    page.on('pageerror',lambda e:errors.append(str(e)))
    idle(page)
    check('Dashboard renders all four endpoints',page.locator('.svg-node').count()==4)
    send(page,'A','B','Hello from NetScope!')
    check('UI unicast returns a real recipient ACK','1 / 1' in page.locator('#send-result').inner_text())
    send(page,'C','ALL','Group 01 broadcast: Dhruv, Manan and Armaan.')
