    send(page,'A','B','<img src=x onerror="window.__xss=true">')
    page.locator('[data-tab="inbox"]').click();page.locator('#inbox-node').select_option('B')
    check('HTML-like payload is escaped in both logs and inbox',not page.evaluate('Boolean(window.__xss)') and page.locator('#records-content img').count()==0)
    page.locator('#node-count').select_option('8');page.locator('#apply-config').click();idle(page)
    check('Configuration creates eight real peers and 28 links',page.evaluate('state.count===8 && state.stats.activeLinks===28'))
