    page.locator('[data-tab="messages"]').click()
    page.locator('#message-text').fill('Hello from NetScope!')
    page.screenshot(path=str(EVIDENCE/'01-client-server-ui.png'),full_page=True)
    page.locator('.lab-grid').screenshot(path=str(EVIDENCE/'01-client-server-lab.png'))
    page.locator('#hub-toggle').click();idle(page)
    send(page,'A','B','Testing the central point of failure.')
    check('Hub failure is visible as a failed UI delivery','Central server is offline' in page.locator('#send-result').inner_text())
