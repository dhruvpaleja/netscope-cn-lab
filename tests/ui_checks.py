    send(page,'D','A','नमस्ते 🌐 — UTF-8 verified over TCP.')
    check('Unicode delivery succeeds','1 / 1' in page.locator('#send-result').inner_text())
    page.locator('[data-tab="inbox"]').click()
    page.locator('#inbox-node').select_option('A')
    check('Inbox displays actual decoded Unicode payload','नमस्ते' in page.locator('#records-content').inner_text())
    page.locator('[data-tab="sockets"]').click()
